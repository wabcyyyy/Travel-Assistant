def main() -> None:
    rng = random.Random(42)
    lines: list[str] = [
        "-- 由 sql/generate_seed.py 生成，勿手改",
        "USE travel_assistant;",
        "",
        "INSERT INTO city_consumption (city, level, meal_price, transport_price, hotel_price) VALUES",
    ]
    consumption_rows = []
    for city, (level, meal, transport, hotel) in CITY_CONSUMPTION.items():
        consumption_rows.append(f"    ('{city}', '{level}', {meal:.2f}, {transport:.2f}, {hotel:.2f})")
    lines.append(",\n".join(consumption_rows) + ";")
    lines.append("")
    lines.append("INSERT INTO poi_knowledge (id, city, name, category, latitude, longitude, ticket_price, duration_min, open_time, tags, rating, description) VALUES")
    poi_rows = []
    poi_id = 1
    for city, entries in POIS.items():
        base_lng, base_lat = CITY_CENTERS[city]
        for name, price, duration, open_time, tags, rating in entries:
            lng = round(base_lng + rng.uniform(-0.12, 0.12), 6)
            lat = round(base_lat + rng.uniform(-0.08, 0.08), 6)
            category = "food" if price and price < 200 and name and any(
                kw in name for kw in ["店", "巷", "馒头", "生煎", "泡馍", "凉皮", "肉夹馍", "蛋糕", "鸡", "茶", "豆腐", "抄手", "水饺", "肺片", "串串", "海鲜", "包子", "粉"]
            ) else "attraction"
            if category == "food":
                price = round(price, 2)
            price_sql = "NULL" if price is None else f"{price:.2f}"
            rating_sql = "NULL" if rating is None else f"{rating:.1f}"
            type_cn = "美食" if category == "food" else "景点"
            tag_cn = tags.replace(",", "/")
            description = f"{city}热门{type_cn}打卡地，适合{tag_cn}出行体验。"
            poi_rows.append(
                f"    ({poi_id}, '{city}', '{name}', '{category}', {lat}, {lng}, {price_sql}, {duration}, '{open_time}', '{tags}', {rating_sql}, '{description}')"
            )
            poi_id += 1
    lines.append(",\n".join(poi_rows) + ";")
    output_path = Path(__file__).resolve().parent / "seed_data.sql"
    output_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"generated {output_path}")


if __name__ == "__main__":
    main()
